    void applyRelations(QVector<TweakSpec>& c)
    {
        QHash<QString, qsizetype> byId;
        byId.reserve(c.size());
        for (qsizetype i = 0; i < c.size(); ++i)
            byId.insert(c.at(i).id, i);

        for (const Pair& p : kMutuallyExclusive) {
            const QString a = QString::fromLatin1(p.a);
            const QString b = QString::fromLatin1(p.b);
            const qsizetype ia = byId.value(a, -1);
            const qsizetype ib = byId.value(b, -1);
            // A stale id still lands in the surviving spec's excludes so the
            // relation check reports it rather than it silently vanishing.
            if (ia >= 0 && !c[ia].excludes.contains(b))
                c[ia].excludes.append(b);
            if (ib >= 0 && !c[ib].excludes.contains(a))
                c[ib].excludes.append(a);
        }
    }
