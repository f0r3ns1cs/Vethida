#!/usr/bin/env node
// Updates Vethida/translations/vethida_<lang>.ts with lupdate.
//   node scripts/translations.mjs update --qt C:\Qt\6.11.1\msvc2022_64\bin de fr
// The tweak catalog strings aren't tr() calls, so they get dumped into
// out/translations/catalog-strings.h first (context "Tweaks").

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tweaksDir = path.join(root, "Vethida", "vth_core", "Tweaks");
const tsDir = path.join(root, "Vethida", "translations");
const outDir = path.join(root, "out", "translations");

const literal = /"((?:[^"\\]|\\.)*)"/g;
const joined = (text) => [...text.matchAll(literal)].map((m) => m[1]).join("");

function catalogStrings() {
  const strings = new Set();
  for (const file of fs.readdirSync(tweaksDir).filter((f) => /^TweakCatalog.*\.cpp$/.test(f))) {
    const src = fs.readFileSync(path.join(tweaksDir, file), "utf8");
    for (const m of src.matchAll(/t\.(?:name|description|subCategory)\s*=\s*QStringLiteral\(((?:\s*"(?:[^"\\]|\\.)*")+)\s*\)/g))
      strings.add(joined(m[1]));
    for (const m of src.matchAll(/t\.(?:warnings|effects)\s*=\s*\{([\s\S]*?)\};/g))
      for (const item of m[1].matchAll(/QStringLiteral\(((?:\s*"(?:[^"\\]|\\.)*")+)\s*\)/g))
        strings.add(joined(item[1]));
  }
  strings.delete("");
  return [...strings];
}

function writeCatalogStrings() {
  const strings = catalogStrings();
  fs.mkdirSync(outDir, { recursive: true });
  const body = strings.map((s) => `QT_TRANSLATE_NOOP("Tweaks", "${s}")`).join("\n");
  fs.writeFileSync(path.join(outDir, "catalog-strings.h"), `// Generated by scripts/translations.mjs. Do not edit.\n${body}\n`);
  console.log(`${strings.length} catalog strings collected`);
}

function update(qtBin, langs) {
  const lupdate = path.join(qtBin, process.platform === "win32" ? "lupdate.exe" : "lupdate");
  if (!fs.existsSync(lupdate)) throw new Error(`lupdate not found in ${qtBin}`);
  fs.mkdirSync(tsDir, { recursive: true });
  if (langs.length === 0)
    langs = fs.readdirSync(tsDir).flatMap((f) => /^vethida_(.+)\.ts$/.exec(f)?.[1] ?? []);
  if (langs.length === 0) throw new Error("Name at least one language, for example: de");
  writeCatalogStrings();
  const ts = langs.map((l) => path.join(tsDir, `vethida_${l}.ts`));
  execFileSync(lupdate, [
    "-locations", "relative",
    path.join(root, "Vethida", "gui"),
    path.join(root, "Vethida", "vth_core"),
    outDir,
    "-ts", ...ts,
  ], { stdio: "inherit" });
}

const [command, ...rest] = process.argv.slice(2);
const qtAt = rest.indexOf("--qt");
const qtBin = qtAt >= 0 ? rest[qtAt + 1] : undefined;
const langs = rest.filter((_, i) => i !== qtAt && i !== qtAt + 1);

if (command === "update" && qtBin) update(qtBin, langs);
else if (command === "strings") writeCatalogStrings();
else {
  console.log("usage: node scripts/translations.mjs update --qt <Qt bin> [lang ...]");
  console.log("       node scripts/translations.mjs strings");
  process.exit(command ? 1 : 0);
}
